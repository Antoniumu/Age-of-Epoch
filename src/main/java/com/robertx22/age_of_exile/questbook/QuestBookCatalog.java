    public static List<Chapter> chapters() {
        return CHAPTERS;
    }

    public static int storyChapterCount() {
        return (int) CHAPTERS.stream().filter(chapter -> !chapter.platinum()).count();
    }

    public static Chapter findChapter(String id) {
        return CHAPTERS.stream().filter(chapter -> chapter.id().equals(id)).findFirst().orElse(null);
    }

    public static Objective findObjective(String id) {
        for (Chapter chapter : CHAPTERS) {
            for (Objective objective : chapter.objectives()) {
                if (objective.id().equals(id)) {
                    return objective;
                }
            }
        }
        return null;
    }
