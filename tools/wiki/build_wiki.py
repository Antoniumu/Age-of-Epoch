def gem_page(g):
    rows = []
    for ru, en, multi, chance, weight in GEM_RANKS:
        rows.append("| {ru} ({en}) | ×{m} | {a}{asfx} | {j}{jsfx} | {w}{wsfx} |".format(
            ru=ru, en=en, m=fmt(multi),
            a=fmt(g["armor"][1] * multi), asfx=g["armor"][2],
            j=fmt(g["jewelry"][1] * multi), jsfx=g["jewelry"][2],
            w=fmt(g["weapon"][1] * multi), wsfx=g["weapon"][2]))

    upgrade_rows = []
    for i, (ru, en, multi, chance, weight) in enumerate(GEM_RANKS):
        nxt = GEM_RANKS[i + 1][0] if i + 1 < len(GEM_RANKS) else "—"
        upgrade_rows.append(f"| {ru} → {nxt} | {'—' if chance == 0 else str(chance) + ' %'} |")

    return f"""
{g['lead']}

## Три слота — три разных камня

Самоцвет в этом моде не имеет одного фиксированного эффекта. Он смотрит, **куда** его вставили,
и превращается в три разных предмета:

- в **броне** (шлем, нагрудник, штаны, ботинки) — {g['armor'][0]} до +{fmt(g['armor'][1])}{g['armor'][2]};
- в **украшениях** (кольцо, ожерелье) — {g['jewelry'][0]} до +{fmt(g['jewelry'][1])}{g['jewelry'][2]};
- в **оружии** — {g['weapon'][0]} до +{fmt(g['weapon'][1])}{g['weapon'][2]}.

Числа в таблице ниже — то, что видно в подсказке предмета на максимальном ранге.
Более слабые ранги дают ту же характеристику, умноженную на свой множитель.

## Ранги: от треснувшего до божественного

| Ранг | Множитель | На броне | На бижутерии | На оружии |
|---|---|---|---|---|
{chr(10).join(rows)}

Всего семь рангов, и они не взаимозаменяемы: божественный {g['ru'].lower()} в восемь-десять раз
сильнее треснувшего. Именно поэтому один хороший камень почти всегда выгоднее четырёх плохих —
и именно поэтому за божественными рангами стоит охотиться отдельно.

## Как вставить камень

1. Возьми снаряжение с **сокетом** (пустое гнездо видно в подсказке предмета).
2. Держи самоцвет в руке и примени его к предмету — камень займёт свободный сокет.
3. В один предмет нельзя вставить два одинаковых камня: игра не даст это сделать.
4. Самоцветы стихий ({link('gems/ruby','рубин')}, {link('gems/emerald','изумруд')},
   {link('gems/sapphire','сапфир')}) вставляются по тем же правилам, но усиливают конкретную стихию.

Сокеты бывают пустыми и «занятыми» — см. {link(REF_SOCKETS, 'сокеты и вставки')}.

## Как улучшить ранг

Три одинаковых камня одного ранга можно сжать в один камень следующего ранга.
Шанс успеха падает с рангом:

| Улучшение | Шанс успеха |
|---|---|
{chr(10).join(upgrade_rows)}

При неудаче **все три камня уничтожаются**, а не остаются на месте. Поэтому улучшать
божественные ранги «на удачу» — плохая идея: проще найти их в мире.

## Где искать

- Самоцветы падают с мобов (базовый шанс капли — половина процента) и из сундуков подземелий.
- Чем выше уровень локации, тем больше шанс на высокий ранг: треснувшие и со сколом
  встречаются почти всегда, а славные и божественные — редкость.
- Ящики самоцветов дают сразу несколько камней и часто выпадают за сезонные задания.

## С чем сочетается {g['role'] if g['role'].startswith('кам') else ''}

{g['tips']}

Учитывай {link(REF_SOCKETS, 'правила сокетов')} и {link(REF_RARITY, 'редкость снаряжения')}:
на предметах низкой редкости сокетов меньше, и каждый камень становится дороже.

## Частые ошибки

- Вставлять {g['ru'].lower()} в предмет, который собираешься выбросить через час.
- Улучшать камни «пачкой», не проверив, что все три — одного ранга и одного типа.
- Забывать, что на броне, украшениях и оружии эффект **разный** — один и тот же камень
  в разных слотах не сравнивают напрямую.

## Смотрите также

{link(REF_GEMS, 'Все самоцветы')} · {link(REF_SOCKETS, 'Сокеты')} ·
{link(REF_GEAR, 'Снаряжение')} · {link('uniques/overview', 'Уникальное снаряжение')} ·
{link(REF_CURRENCY, 'Валюта и сферы')}
"""


