def read_java(*parts):
    path = os.path.join(JAVA, *parts)
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def pretty_stat(expr):
    text = expr.strip()
    for needle, name in STAT_WORDS:
        if needle in text:
            return name
    cleaned = re.sub(r"\s+", "", text)
    cleaned = cleaned.replace("new", "").replace(".getInstance()", "").replace(".get()", "")
    return cleaned if cleaned else "характеристика"


def split_top_level(text):
    """Делит строку по запятым верхнего уровня (учитывая скобки)."""
    parts, depth, current = [], 0, []
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
    if current:
        parts.append("".join(current).strip())
    return [p for p in parts if p]


def parse_ingredients():
    base = os.path.join(JAVA, "com", "robertx22", "age_of_exile", "aoe_data", "database", "ingredient")
    items_reg = read_java("com", "robertx22", "age_of_exile", "mmorpg", "registers", "common", "items",
                          "IngredientItems.java")
    const_to_id, const_to_en = {}, {}
    for match in re.finditer(r'([A-Z_0-9]+)\s*=\s*of\("([a-z_0-9]+)",\s*"([^"]+)"\)', items_reg):
        const_to_id[match.group(1)] = match.group(2)
        const_to_en[match.group(1)] = match.group(3)

    lang = {}
    lang_path = os.path.join(ROOT, "src", "main", "resources", "assets", "mmorpg", "lang", "ru_ru.json")
    if os.path.exists(lang_path):
        import json
        with open(lang_path, encoding="utf-8") as handle:
            raw = json.load(handle)
        for key, value in raw.items():
            if key.startswith("item.mmorpg.ingredient."):
                lang[key.split(".")[-1]] = value

    found = {}
    for filename in ("SlashIngredientsAdder.java", "EpicIngredientsAdder.java", "SpecialIngredientsAdder.java",
                     "GridIngredientsAdder.java", "GridPlusStatsAdder.java"):
        path = os.path.join(base, filename)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
        for block in text.split("IngredientBuilder.of(")[1:]:
            match = re.match(r"\s*IngredientItems\.([A-Z_0-9]+)", block)
            if not match:
                continue
            const = match.group(1)
            ing_id = const_to_id.get(const, const.lower())
            body = block[:block.find(".build()") if ".build()" in block else 400]
            professions = re.findall(r"allowedIn\(PlayerSkillEnum\.([A-Z_]+)\)", body)
            rarity = re.search(r"IRarity\.([A-Z_0-9]+)", body)
            stats = []
            for stat in re.finditer(r"new StatModifier\(", body):
                start = stat.end()
                depth, end = 1, start
                while end < len(body) and depth > 0:
                    if body[end] == "(":
                        depth += 1
                    elif body[end] == ")":
                        depth -= 1
                    end += 1
                args = split_top_level(body[start:end - 1])
                if len(args) >= 3:
                    try:
                        low, high = float(args[0]), float(args[1])
                    except ValueError:
                        continue
                    percent = "PERCENT" in (args[3] if len(args) > 3 else "")
                    prefix = "" if percent else ""
                    name = pretty_stat(args[2])
                    if low == high:
                        stats.append(f"{name} {fmt(low)}{' %' if percent else ''}")
                    else:
                        stats.append(f"{name} {fmt(low)}…{fmt(high)}{' %' if percent else ''}")
            entry = {
                "id": ing_id,
                "en": const_to_en.get(const, ing_id),
                "ru": lang.get(ing_id, const_to_en.get(const, ing_id)),
                "prof": [PROFESSIONS_RU.get(p, p) for p in professions],
                "rarity": RARITY_RU.get(rarity.group(1) if rarity else "", "обычный"),
                "stats": stats,
            }
            if ing_id not in found:
                found[ing_id] = entry
    return list(found.values())


